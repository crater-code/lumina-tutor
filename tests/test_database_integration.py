class TestDatabaseWithChunking:
    """Test database integration with chunking engine."""
    
    def test_store_chunks_from_chunking_engine(self, temp_db, chunking_engine):
        """Test storing chunks generated by the chunking engine."""
        # Create a book
        book_id = str(uuid.uuid4())
        temp_db.create_book(
            book_id=book_id,
            title="Test Book",
            filename="test.pdf",
            page_count=10
        )
        
        # Create some page content
        pages = [
            PageContent(
                page_number=1,
                text="This is the first page. It contains some introductory text about the topic.",
                metadata={}
            ),
            PageContent(
                page_number=2,
                text="This is the second page. It continues the discussion with more details.",
                metadata={}
            )
        ]
        
        # Generate chunks
        chunks = chunking_engine.create_chunks(pages, book_id=book_id)
        
        # Store chunks in database
        for chunk in chunks:
            temp_db.create_chunk(
                chunk_id=chunk.chunk_id,
                book_id=book_id,  # Use the book_id from the test
                text=chunk.text,
                page_numbers=chunk.page_numbers,
                start_char=chunk.start_char,
                end_char=chunk.end_char,
                metadata=chunk.metadata
            )
        
        # Verify chunks are stored
        stored_chunks = temp_db.list_chunks_by_book(book_id)
        assert len(stored_chunks) == len(chunks)
        
        # Verify chunk data matches
        for i, stored_chunk in enumerate(stored_chunks):
            assert stored_chunk["chunk_id"] == chunks[i].chunk_id
            assert stored_chunk["text"] == chunks[i].text
            assert stored_chunk["page_numbers"] == chunks[i].page_numbers
    
