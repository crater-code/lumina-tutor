"""
Integration tests for ResponseValidator with ChatbotEngine.

These tests verify that the ResponseValidator correctly validates
responses generated by the ChatbotEngine.
"""

import pytest
from src.response_validator import ResponseValidator
from src.chatbot_engine import ChatbotEngine
from src.models import Chunk


class TestResponseValidatorIntegration:
    """Integration tests for ResponseValidator with ChatbotEngine."""
    
    @pytest.fixture
    def validator(self):
        """Create a ResponseValidator instance."""
        return ResponseValidator()
    
    @pytest.fixture
    def chatbot_engine(self):
        """Create a ChatbotEngine instance."""
        return ChatbotEngine()
    
    @pytest.fixture
    def sample_chunks(self):
        """Create sample chunks about photosynthesis."""
        return [
            Chunk(
                chunk_id="book_1_chunk_1",
                text="Photosynthesis is the process by which plants use sunlight to convert carbon dioxide and water into glucose and oxygen. This process occurs in the chloroplasts of plant cells.",
                page_numbers=[1],
                start_char=0,
                end_char=160,
                metadata={}
            ),
            Chunk(
                chunk_id="book_1_chunk_2",
                text="The chlorophyll in plant leaves captures light energy from the sun. This energy is used to power the chemical reactions that produce glucose, which plants use for food.",
                page_numbers=[1],
                start_char=161,
                end_char=320,
                metadata={}
            )
        ]
    
    def test_valid_chatbot_response_passes_validation(
        self,
        validator,
        chatbot_engine,
        sample_chunks
    ):
        """Test that a valid response from ChatbotEngine passes validation."""
        # Generate response
        response = chatbot_engine.generate_response(
            query="What is photosynthesis?",
            retrieved_chunks=sample_chunks,
            user_age=10,
            language="en"
        )
        
        # Validate response
        result = validator.validate_response(response, sample_chunks)
        
        # Should pass validation
        assert result.is_valid is True
        assert len(result.issues) == 0
        assert response.chunk_ids == ["book_1_chunk_1", "book_1_chunk_2"]
    
    def test_refusal_message_passes_validation(
        self,
        validator,
        chatbot_engine
    ):
        """Test that refusal messages pass validation."""
        # Generate refusal
        response = chatbot_engine.generate_refusal(
            query="What is quantum mechanics?",
            user_age=10,
            language="en"
        )
        
        # Validate response (no chunks needed for refusal)
        result = validator.validate_response(response, [])
        
        # Should pass validation
        assert result.is_valid is True
        assert response.is_refusal is True
        assert len(response.chunk_ids) == 0
    
    def test_response_with_different_age_groups(
        self,
        validator,
        chatbot_engine,
        sample_chunks
    ):
        """Test validation of responses for different age groups."""
        age_groups = [5, 10, 14]
        
        for age in age_groups:
            # Generate response
            response = chatbot_engine.generate_response(
                query="How do plants make food?",
                retrieved_chunks=sample_chunks,
                user_age=age,
                language="en"
            )
            
            # Validate response
            result = validator.validate_response(response, sample_chunks)
            
            # All age-adapted responses should pass validation
            assert result.is_valid is True, f"Failed for age {age}"
            assert response.metadata["age_group"] in [
                "young_child", "elementary", "middle_school"
            ]
    
    def test_multilingual_response_validation(
        self,
        validator,
        chatbot_engine,
        sample_chunks
    ):
        """Test validation of responses in different languages."""
        languages = ["en", "ur"]
        
        for language in languages:
            # Generate response
            response = chatbot_engine.generate_response(
                query="What is photosynthesis?",
                retrieved_chunks=sample_chunks,
                user_age=10,
                language=language
            )
            
            # Validate response
            result = validator.validate_response(response, sample_chunks)
            
            # Both English and Urdu responses should pass validation
            assert result.is_valid is True, f"Failed for language {language}"
            assert response.metadata["language"] == language
    
