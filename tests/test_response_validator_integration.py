    def test_validation_workflow_with_multiple_queries(
        self,
        validator,
        chatbot_engine,
        sample_chunks
    ):
        """Test validation workflow with multiple queries."""
        queries = [
            "What is photosynthesis?",
            "How do plants use sunlight?",
            "What do plants produce?"
        ]
        
        for query in queries:
            # Generate response
            response = chatbot_engine.generate_response(
                query=query,
                retrieved_chunks=sample_chunks,
                user_age=10,
                language="en"
            )
            
            # Validate response
            result = validator.validate_response(response, sample_chunks)
            
            # All responses should pass validation
            assert result.is_valid is True, f"Failed for query: {query}"
