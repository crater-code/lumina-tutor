    def test_validation_confidence_varies_by_response_quality(
        self,
        validator,
        chatbot_engine,
        sample_chunks
    ):
        """Test that validation confidence reflects response quality."""
        # Generate a response
        response = chatbot_engine.generate_response(
            query="What is photosynthesis?",
            retrieved_chunks=sample_chunks,
            user_age=10,
            language="en"
        )
        
        # Validate response
        result = validator.validate_response(response, sample_chunks)
        
        # Valid responses should have high confidence
        assert result.is_valid is True
        assert result.confidence > 0.5
    
    def test_end_to_end_validation_workflow(
        self,
        validator,
        chatbot_engine
    ):
        """Test complete end-to-end validation workflow."""
        # Step 1: Create chunks
        chunks = [
            Chunk(
                chunk_id="book_1_chunk_1",
                text="Water is essential for life. All living organisms need water to survive.",
                page_numbers=[1],
                start_char=0,
                end_char=80,
                metadata={}
            )
        ]
        
        # Step 2: Generate response
        response = chatbot_engine.generate_response(
            query="Why is water important?",
            retrieved_chunks=chunks,
            user_age=8,
            language="en"
        )
        
        # Step 3: Validate response
        result = validator.validate_response(response, chunks)
        
        # Step 4: Verify complete workflow
        assert result.is_valid is True
        assert response.chunk_ids == ["book_1_chunk_1"]
        assert not response.is_refusal
        assert response.metadata["age_group"] == "elementary"
        assert response.metadata["language"] == "en"
    
    def test_validation_with_empty_chunks_list(
        self,
        validator,
        chatbot_engine
    ):
        """Test that validation fails when chunks list is empty for non-refusal."""
        # This should raise an error in generate_response
        with pytest.raises(ValueError, match="Retrieved chunks cannot be empty"):
            chatbot_engine.generate_response(
                query="What is photosynthesis?",
                retrieved_chunks=[],  # Empty chunks
                user_age=10,
                language="en"
            )
    
    def test_refusal_validation_with_different_ages(
        self,
        validator,
        chatbot_engine
    ):
        """Test that refusal messages for different ages all pass validation."""
        age_groups = [5, 10, 14]
        
        for age in age_groups:
            # Generate refusal
            response = chatbot_engine.generate_refusal(
                query="What is quantum mechanics?",
                user_age=age,
                language="en"
            )
            
            # Validate response
            result = validator.validate_response(response, [])
            
            # All refusals should pass validation
            assert result.is_valid is True, f"Failed for age {age}"
            assert response.is_refusal is True
            assert result.confidence == 1.0


